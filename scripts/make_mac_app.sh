#!/usr/bin/env sh
# Build Blanks.app, a macOS launcher you can keep in the Dock.
#
#   scripts/make_mac_app.sh [install folder]     (default: ~/Applications)
#
# Clicking it starts the Blanks server in the background if it isn't
# running, then opens Blanks in its own window. The server stops by itself
# about ten minutes after the last Blanks window closes. The app points at
# this checkout, so run the script again if you move the folder.
set -e

[ "$(uname)" = "Darwin" ] || { echo "Blanks.app is for macOS only."; exit 1; }

REPO="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$HOME/Applications}"
APP="$DEST/Blanks.app"
UV_DIR="$(dirname "$(command -v uv)")" || { echo "Install uv first."; exit 1; }
NPM_DIR="$(dirname "$(command -v npm)")" || { echo "Install Node.js first."; exit 1; }
CLAUDE_DIR="$(dirname "$(command -v claude 2>/dev/null || echo "$HOME/.local/bin/claude")")"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "Building the icon..."
qlmanage -t -s 1024 -o "$WORK" "$REPO/assets/icon.svg" >/dev/null 2>&1
SRC="$WORK/icon.svg.png"
[ -f "$SRC" ] || { echo "Couldn't render assets/icon.svg."; exit 1; }
SET="$WORK/Blanks.iconset"
mkdir "$SET"
for size in 16 32 128 256 512; do
  sips -z $size $size "$SRC" --out "$SET/icon_${size}x${size}.png" >/dev/null
  double=$((size * 2))
  sips -z $double $double "$SRC" --out "$SET/icon_${size}x${size}@2x.png" >/dev/null
done

echo "Building $APP..."
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
iconutil -c icns "$SET" -o "$APP/Contents/Resources/Blanks.icns"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Blanks</string>
  <key>CFBundleDisplayName</key><string>Blanks</string>
  <key>CFBundleIdentifier</key><string>com.github.blanks-pdf.launcher</string>
  <key>CFBundleExecutable</key><string>Blanks</string>
  <key>CFBundleIconFile</key><string>Blanks</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>0.1.0</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>LSArchitecturePriority</key><array><string>arm64</string><string>x86_64</string></array>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/Blanks" <<LAUNCHER
#!/bin/sh
# Generated by scripts/make_mac_app.sh. Starts Blanks and opens its window.
export PATH="$UV_DIR:$NPM_DIR:$CLAUDE_DIR:/usr/local/bin:\$PATH"
REPO="$REPO"
LOG="\$HOME/Library/Logs/Blanks.log"
if [ ! -x "\$REPO/start" ]; then
  osascript -e 'display alert "Blanks can'"'"'t find its folder" message "Run scripts/make_mac_app.sh again from the Blanks folder."'
  exit 1
fi
cd "\$REPO"
# Script launchers can be started under Rosetta; run natively on Apple silicon.
if [ "\$(sysctl -n hw.optional.arm64 2>/dev/null)" = "1" ]; then
  nohup arch -arm64 /bin/sh ./start --idle-exit 10 >> "\$LOG" 2>&1 &
else
  nohup ./start --idle-exit 10 >> "\$LOG" 2>&1 &
fi
LAUNCHER
chmod +x "$APP/Contents/MacOS/Blanks"

# Make Finder and the Dock pick up the new icon.
touch "$APP"
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$APP" >/dev/null 2>&1 || true

echo "Done. Open $APP, then right-click its Dock icon > Options > Keep in Dock."
